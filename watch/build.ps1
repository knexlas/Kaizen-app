# Builds the Kaizen Plan watch app (.prg) for a fenix 8.
#   .\build.ps1                       -> bin\KaizenPlan.prg for fenix847mm
#   .\build.ps1 -Device fenix8solar51mm
#   .\build.ps1 -Run                  -> also start it in the Connect IQ simulator
# Needs: Connect IQ SDK (via the SDK Manager, with the fenix 8 device files) and Java 17+.
param(
    [string]$Device = "fenix847mm",
    [switch]$Run
)
$ErrorActionPreference = "Stop"
$here = $PSScriptRoot

# 1. Firebase settings for the watch come from the web app's .env (source/Config.mc is gitignored).
$envFile = Join-Path $here "..\.env"
if (-not (Test-Path $envFile)) { throw "Missing ..\.env with VITE_FIREBASE_PROJECT_ID and VITE_FIREBASE_API_KEY" }
$vars = @{}
Get-Content $envFile | Where-Object { $_ -match '^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$' } | ForEach-Object {
    $vars[$Matches[1]] = $Matches[2].Trim('"', "'", ' ')
}
$projectId = $vars["VITE_FIREBASE_PROJECT_ID"]
$apiKey = $vars["VITE_FIREBASE_API_KEY"]
if (-not $projectId -or -not $apiKey) { throw ".env needs VITE_FIREBASE_PROJECT_ID and VITE_FIREBASE_API_KEY" }
@"
// Generated by build.ps1 from ../.env. Do not commit.
(:background)
module Config {
    const PROJECT_ID = "$projectId";
    const API_KEY = "$apiKey";
}
"@ | Set-Content -Encoding utf8 (Join-Path $here "source\Config.mc")

# 2. Connect IQ SDK
$cfg = Join-Path $env:APPDATA "Garmin\ConnectIQ\current-sdk.cfg"
if (-not (Test-Path $cfg)) { throw "Connect IQ SDK not found. Install it with the SDK Manager: https://developer.garmin.com/connect-iq/sdk/" }
$sdk = (Get-Content $cfg -Raw).Trim()
$bin = Join-Path $sdk "bin"

# 3. Developer key (created once; keep it, sideloaded updates must use the same key)
$key = Join-Path $here "developer_key.der"
if (-not (Test-Path $key)) {
    $openssl = (Get-Command openssl -ErrorAction SilentlyContinue).Source
    if (-not $openssl -and (Test-Path "C:\Program Files\Git\usr\bin\openssl.exe")) { $openssl = "C:\Program Files\Git\usr\bin\openssl.exe" }
    if (-not $openssl) { throw "No developer_key.der and no openssl to create one." }
    $pem = Join-Path $here "developer_key.pem"
    & $openssl genrsa -out $pem 4096
    & $openssl pkcs8 -topk8 -inform PEM -outform DER -in $pem -out $key -nocrypt
}

# 4. Build
New-Item -ItemType Directory -Force (Join-Path $here "bin") | Out-Null
$out = Join-Path $here "bin\KaizenPlan.prg"
& (Join-Path $bin "monkeyc.bat") -d $Device -f (Join-Path $here "monkey.jungle") -o $out -y $key -l 0 -w
if ($LASTEXITCODE -ne 0) { throw "monkeyc failed" }
Write-Host "Built $out"

if ($Run) {
    Start-Process (Join-Path $bin "connectiq.bat")
    Start-Sleep -Seconds 3
    & (Join-Path $bin "monkeydo.bat") $out $Device
}
